<#
.SYNOPSIS
    AI 3D Forge -- build the distributable release folder.

.DESCRIPTION
    Produces build\release\ containing everything needed to hand the software to
    someone else's computer:

      AI-3D-Forge-Setup.exe         the one-click installer
      CHECKSUMS.txt                 SHA-256, so the recipient can verify the file
      release-info.txt              build metadata for support
      README-<localized>.md         the quick-start guide
      LICENSE                       the project licence (MIT)
      LICENSE-THIRD-PARTY.txt       third-party components and their licences
      LICENSE-OpenSCAD-GPLv2.txt    OpenSCAD's GPLv2 text (required: we install it)
      <localized guide>.txt         written by make_release_docs.py

    It verifies before declaring success: the installer exists, carries version
    metadata, is not absurdly small, its checksum matches the checksum file, and
    the GPLv2 text really is the full licence.

    IMPORTANT: this script is ASCII-only (see the developer README, section 10).
    Windows PowerShell 5.1 decodes a BOM-less .ps1 as the system ANSI code page,
    which corrupts non-ASCII text. Chinese documents are therefore generated by
    scripts\make_release_docs.py (Python handles UTF-8 correctly), and Chinese
    filenames are referred to by wildcard rather than by literal.

.EXAMPLE
    .\scripts\make_release.ps1
    .\scripts\make_release.ps1 -SkipBuild
#>

[CmdletBinding()]
param(
    [switch]$SkipBuild
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$Work = Join-Path $Root 'build\work'
$env:TMP = Join-Path $Root 'build\cache\tmp'
$env:TEMP = $env:TMP
New-Item -ItemType Directory -Force -Path $Work | Out-Null

function Write-Ok   { param([string]$T) Write-Host "  [OK]   $T" -ForegroundColor Green }
function Write-Warn { param([string]$T) Write-Host "  [WARN] $T" -ForegroundColor Yellow }
function Write-Err  { param([string]$T) Write-Host "  [FAIL] $T" -ForegroundColor Red }

$Python = Join-Path $Root 'build\venv\Scripts\python.exe'
$Setup = Join-Path $Root 'installer\Output\AI-3D-Forge-Setup.exe'

if (-not $SkipBuild) {
    Write-Host ''
    Write-Host '  Step 1/3  Building the installer (a few minutes)' -ForegroundColor Cyan
    & (Join-Path $PSScriptRoot 'build.ps1') -SkipFrontend
    if ($LASTEXITCODE -ne 0) {
        Write-Err 'The build failed; no release folder was produced.'
        exit 1
    }
} else {
    Write-Host ''
    Write-Host '  Step 1/3  Reusing the existing installer (-SkipBuild)' -ForegroundColor Cyan
}

if (-not (Test-Path $Setup)) {
    Write-Err "Installer not found: $Setup"
    exit 1
}

# --------------------------------------------------------------------------
Write-Host ''
Write-Host '  Step 2/3  Assembling the release folder' -ForegroundColor Cyan

$Release = Join-Path $Root 'build\release'
if (Test-Path $Release) { Remove-Item $Release -Recurse -Force }
New-Item -ItemType Directory -Force -Path $Release | Out-Null

Copy-Item $Setup (Join-Path $Release 'AI-3D-Forge-Setup.exe') -Force

# Copy the localized guides. Requirement 47 asks for BOTH a user guide and a
# developer guide, so both README-*.md files ship: a curious owner (or their IT
# person) should not have to hunt for the source package to understand the tool.
# Match by wildcard because the Chinese filenames cannot be written literally in
# an ASCII-only script.
$copied = 0
Get-ChildItem $Root -Filter 'README-*.md' -File | ForEach-Object {
    Copy-Item $_.FullName (Join-Path $Release $_.Name) -Force
    $copied++
}
foreach ($name in @('LICENSE-THIRD-PARTY.txt', 'LICENSE-OpenSCAD-GPLv2.txt')) {
    $source = Join-Path $Root "docs\$name"
    if (Test-Path $source) {
        Copy-Item $source (Join-Path $Release $name) -Force
    } else {
        Write-Warn "Missing document, skipped: $name"
    }
}
# The project licence itself (MIT) sits at the repository root, not in docs\.
$licence = Join-Path $Root 'LICENSE'
if (Test-Path $licence) {
    Copy-Item $licence (Join-Path $Release 'LICENSE') -Force
} else {
    Write-Warn 'Missing document, skipped: LICENSE'
}
# The quick-start README links to docs/<guide>, so the full guides have to travel
# with it in the same relative layout (otherwise the link is dead for the user who
# only received the release folder).
$docsOut = Join-Path $Release 'docs'
New-Item -ItemType Directory -Force -Path $docsOut | Out-Null
foreach ($name in @('USER_GUIDE.md', 'DEVELOPMENT.md', 'OPENSCAD-SOURCES.md')) {
    $source = Join-Path $Root "docs\$name"
    if (Test-Path $source) {
        Copy-Item $source (Join-Path $docsOut $name) -Force
    } else {
        Write-Warn "Missing document, skipped: docs\$name"
    }
}
if ($copied -lt 1) { Write-Warn 'No localized README was found to copy.' }

$setupInfo = Get-Item (Join-Path $Release 'AI-3D-Forge-Setup.exe')
$hash = (Get-FileHash $setupInfo.FullName -Algorithm SHA256).Hash
# Inno pads the version resource with trailing spaces; trim so the metadata files
# do not carry "1.0.0          " into release-info.txt and the console output.
$version = "$($setupInfo.VersionInfo.FileVersion)".Trim()
$sizeMb = [math]::Round($setupInfo.Length / 1MB, 2)
$builtAt = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
$utf8 = New-Object System.Text.UTF8Encoding($false)

$checksums = @(
    "AI 3D Forge $version",
    'SHA-256 checksums',
    '',
    "$hash  AI-3D-Forge-Setup.exe",
    '',
    'Verify on Windows (PowerShell):',
    '    Get-FileHash .\AI-3D-Forge-Setup.exe -Algorithm SHA256',
    'The printed hash must match the line above.'
) -join "`r`n"
[System.IO.File]::WriteAllText((Join-Path $Release 'CHECKSUMS.txt'), $checksums, $utf8)

$info = @(
    'AI 3D Forge -- release information',
    '==================================',
    'Product      : AI 3D Forge',
    "Version      : $version",
    "Built at     : $builtAt",
    "Build ID     : $($env:AIFORGE_BUILD_ID)",
    'Installer    : AI-3D-Forge-Setup.exe',
    "Size         : $sizeMb MB",
    "SHA-256      : $hash",
    'Publisher    : AI 3D Forge',
    '',
    'Requirements',
    '------------',
    'Windows 10 1809 or newer, 64-bit (Windows 11 included).',
    'No Python, no Node.js and no command line are needed.',
    'Internet access is required for AI design (DeepSeek API) and, during first',
    'setup, for downloading the free OpenSCAD engine from its official site.',
    '',
    'Where files live after install',
    '------------------------------',
    'Program       : the folder you choose (default D:\Program Files\AI 3D Forge)',
    'User data     : %APPDATA%\AI-3D-Forge',
    'Projects/STL  : <Documents>\AI-3D-Forge\Projects',
    '',
    'Uninstalling never deletes your projects or your API key.',
    '',
    'Not bundled: OpenSCAD',
    '---------------------',
    'OpenSCAD is GPLv2 and is NOT shipped inside this installer. The setup step',
    'downloads the unmodified official release from files.openscad.org and',
    'verifies its published SHA-256 before installing. Licence text:',
    'LICENSE-OpenSCAD-GPLv2.txt. Source code: https://github.com/openscad/openscad',
    '',
    'Support',
    '-------',
    'The in-app "system diagnostics" page lists every check and offers one-click',
    'repair. Logs live in %LOCALAPPDATA%\AI-3D-Forge\logs.',
    ''
) -join "`r`n"
[System.IO.File]::WriteAllText((Join-Path $Release 'release-info.txt'), $info, $utf8)

# Chinese documents are produced by Python: PowerShell 5.1 cannot be trusted with
# non-ASCII literals, and Python writes UTF-8 correctly.
& $Python (Join-Path $Root 'scripts\make_release_docs.py') $Release $version $builtAt
if ($LASTEXITCODE -ne 0) {
    Write-Err 'Failed to generate the Chinese install guide.'
    exit 1
}

# --------------------------------------------------------------------------
Write-Host ''
Write-Host '  Step 3/3  Verifying the release' -ForegroundColor Cyan

$failures = @()

if ($setupInfo.Length -lt 5MB) { $failures += "installer looks too small ($sizeMb MB)" }
if (-not $version) { $failures += 'installer carries no version metadata' }

$actual = (Get-FileHash (Join-Path $Release 'AI-3D-Forge-Setup.exe') -Algorithm SHA256).Hash
$checksumText = Get-Content (Join-Path $Release 'CHECKSUMS.txt') -Raw
if ($checksumText -notlike "*$actual*") { $failures += 'CHECKSUMS.txt does not match the installer' }

foreach ($required in @('LICENSE', 'LICENSE-THIRD-PARTY.txt', 'LICENSE-OpenSCAD-GPLv2.txt', 'CHECKSUMS.txt', 'release-info.txt')) {
    if (-not (Test-Path (Join-Path $Release $required))) { $failures += "missing document: $required" }
}
# The quick-start guide links into docs\ -- make sure those targets really shipped.
foreach ($name in @('USER_GUIDE.md', 'DEVELOPMENT.md')) {
    if (-not (Test-Path (Join-Path $Release "docs\$name"))) { $failures += "missing document: docs\$name" }
}

# The localized quick-start guide is matched by wildcard (see the note above about
# Chinese filenames in an ASCII-only script). It is deliberately short now -- the
# full guide lives in docs\ -- so the threshold only catches a truncated copy.
$localizedReadme = @(Get-ChildItem $Release -Filter 'README-*.md' -File)
if ($localizedReadme.Count -lt 1) {
    $failures += 'missing the localized user guide'
} elseif ($localizedReadme[0].Length -lt 1500) {
    $failures += "the localized user guide looks truncated ($($localizedReadme[0].Length) bytes)"
}

# The Chinese guide is matched by wildcard so this script stays ASCII-only.
$guide = @(Get-ChildItem $Release -Filter '*.txt' | Where-Object { $_.Name -notin @('CHECKSUMS.txt', 'release-info.txt', 'LICENSE-THIRD-PARTY.txt', 'LICENSE-OpenSCAD-GPLv2.txt') })
if ($guide.Count -lt 1) {
    $failures += 'missing the Chinese install guide'
} elseif ($guide[0].Length -lt 2000) {
    $failures += "the Chinese install guide looks truncated ($($guide[0].Length) bytes)"
}

$gpl = Join-Path $Release 'LICENSE-OpenSCAD-GPLv2.txt'
if (Test-Path $gpl) {
    $gplText = Get-Content $gpl -Raw
    if ($gplText.Length -lt 15000) { $failures += 'GPLv2 text looks truncated' }
    if ($gplText -notmatch 'GNU GENERAL PUBLIC LICENSE') { $failures += 'GPLv2 text is not the real licence' }
}

if ($failures.Count -gt 0) {
    Write-Host ''
    foreach ($f in $failures) { Write-Err $f }
    exit 1
}

$releaseSize = [math]::Round(((Get-ChildItem $Release -File | Measure-Object Length -Sum).Sum / 1MB), 2)

# Also produce a single .zip: many transfer channels (chat, web mail, some cloud
# drives) handle one file far better than a folder.
$zip = Join-Path (Split-Path -Parent $Release) 'AI-3D-Forge-Release.zip'
if (Test-Path $zip) { Remove-Item $zip -Force }
Compress-Archive -Path (Join-Path $Release '*') -DestinationPath $zip -CompressionLevel Optimal
$zipInfo = Get-Item $zip
$zipHash = (Get-FileHash $zip -Algorithm SHA256).Hash

Write-Ok "Release folder ready: $Release"
Write-Ok "Single-file bundle: $zip"
Write-Host ''
Write-Host '  Contents:' -ForegroundColor White
Get-ChildItem $Release | Sort-Object Name | ForEach-Object {
    $kb = [math]::Round($_.Length / 1KB, 1)
    Write-Host ("    {0,-34} {1,10} KB" -f $_.Name, $kb) -ForegroundColor DarkGray
}
Write-Host ''
Write-Host "  Folder  : $releaseSize MB"
Write-Host "  Zip     : $([math]::Round($zipInfo.Length / 1MB, 2)) MB"
Write-Host "  Version : $version"
Write-Host "  SHA-256 : $actual" -ForegroundColor DarkGray
Write-Host "  Zip hash: $zipHash" -ForegroundColor DarkGray
Write-Host ''
Write-Host '  Share the .zip, or the folder as-is.' -ForegroundColor White
Write-Host ''
Write-Host 'RELEASE_COMPLETE'
exit 0
