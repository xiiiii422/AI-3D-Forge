"""AI 3D Forge —— 生成面向安装者的中文文档（安装说明.txt）。

为什么不写在 PowerShell 里：本项目的构建脚本必须保持纯 ASCII ——
Windows PowerShell 5.1 会把无 BOM 的 .ps1 按系统 ANSI 代码页解码，
中文字符串会被破坏（详见 README-开发者.md 第 10 条，已实际踩过两次）。
把中文文档交给 Python 生成，既保证编码正确，也让构建脚本保持干净。

用法：
    python scripts/make_release_docs.py <输出目录> <版本号> <构建时间>
"""

from __future__ import annotations

import sys
from pathlib import Path

INSTALL_GUIDE = """AI 3D Forge 安装说明
====================

这是一个 Windows 桌面软件：用一句话描述你想做的东西，AI 帮你设计出可以直接
3D 打印的模型。你不需要懂编程，也不需要安装 Python、Node.js 或配置环境变量。

--------------------------------------------------------------------
一、安装（大约 2～5 分钟）
--------------------------------------------------------------------

1. 双击 AI-3D-Forge-Setup.exe

2. 如果 Windows 弹出「是否允许此应用对你的设备进行更改」，点击【是】。
   （安装程序需要这个权限来创建开始菜单和桌面快捷方式。）

3. 按提示一路点击【下一步】。安装位置默认会选 D 盘（如果你有 D 盘），
   这样不占用系统盘空间；也可以点【浏览】自己选。

4. 安装过程中会顺便帮你把免费的 3D 建模引擎 OpenSCAD 一起装好
   （约 21MB，视网速 1～3 分钟）。这一步只做一次，之后升级软件不会重复。

   如果这一步没成功，完全不影响软件安装 —— 第一次打开软件时会再引导你一次，
   或者你自己去 https://openscad.org/ 免费下载安装也可以。

5. 安装完成后会创建桌面快捷方式（默认勾选）。

--------------------------------------------------------------------
二、第一次使用（大约 2 分钟）
--------------------------------------------------------------------

1. 双击桌面上的「AI 3D Forge」。

2. 首次启动会出现欢迎向导，它会自动检查你的电脑环境：
   绿色打勾的项目你什么都不用做。

3. 向导会请你选择打印机机型。这一步很重要：不同机器的喷嘴直径和成型范围
   差别很大，选对之后 AI 才知道该给你设计多厚、多大。不确定就选
   「通用 FDM 打印机 220×220×250」。

4. 向导会请你填写 DeepSeek API Key（这是 AI 设计的必需项）：
   - 打开 https://platform.deepseek.com/api_keys 注册并创建一个 Key
   - 把 Key 粘贴到软件里，点【测试连接】确认可用
   - 你的 Key 只保存在你自己的电脑上，不会上传到任何地方

5. 完成后就可以在右侧输入框里描述你想要的模型了，例如：
   「设计一个桌面手机支架，高度100mm。」

--------------------------------------------------------------------
三、常见问题
--------------------------------------------------------------------

Q：Windows 提示「Windows 已保护你的电脑」或 SmartScreen 警告？
A：这是因为安装包没有购买商业代码签名证书（对个人开发者来说成本较高）。
   如果你确认文件来自可信来源，可以点击「更多信息」→「仍要运行」。
   你也可以先用下面的方法核对文件是否被篡改：

   在安装包所在文件夹按住 Shift 右键 →「在此处打开 PowerShell 窗口」，执行：
       Get-FileHash .\\AI-3D-Forge-Setup.exe -Algorithm SHA256
   把结果与 CHECKSUMS.txt 里的值对比，一致即未被篡改。

Q：杀毒软件报警？
A：本软件是使用 PyInstaller 打包的 Python 程序，这类程序偶尔会被误报。
   安装包内没有任何 OpenSCAD 二进制（它是安装时从 OpenSCAD 官网下载并校验的）。
   建议把安装目录加入信任列表。

Q：双击后没反应 / 启动很慢？
A：第一次启动需要初始化运行环境，通常 3 秒左右。如果超过 30 秒，
   打开安装目录下的 logs 文件夹查看日志。

Q：打开的界面在浏览器里而不是独立窗口？
A：说明你的系统缺少微软的 WebView2 运行时组件（Windows 11 和较新的
   Windows 10 都自带）。软件会在页面顶部说明原因并提供一键安装入口。
   功能在任何情况下都完全一致。

Q：安装 OpenSCAD 失败怎么办？
A：软件会告诉你具体原因。你也可以手动安装：
   1) 打开 https://openscad.org/ 下载 Windows 安装包
   2) 双击安装（一路「下一步」）
   3) 回到软件，在「系统诊断」页点【全部重新检测】，会自动识别

Q：安装时提示需要管理员权限？
A：这是 Windows 的正常权限机制，用于创建开始菜单与桌面快捷方式。
   软件不会在未经你同意的情况下做任何系统级改动。

Q：卸载后我的模型会丢吗？
A：不会。卸载时软件会明确告诉你项目保存在哪里，并询问是否一并删除
   （默认保留）。如果以后重新安装，项目会自动回来。

Q：软件需要联网吗？我的数据会被上传吗？
A：设计模型时需要联网（调用你自己配置的 DeepSeek AI）。已经生成好的项目和
   3D 预览完全离线可用。软件不会上传你的模型或项目；唯一的对外请求是
   调用 DeepSeek API，以及在你确认后从 OpenSCAD 官方网站下载引擎。

--------------------------------------------------------------------
四、卸载
--------------------------------------------------------------------

开始菜单 →「AI 3D Forge」→「卸载 AI 3D Forge」，
或在 Windows「设置 → 应用」里找到它卸载。

--------------------------------------------------------------------
五、更多帮助
--------------------------------------------------------------------

软件内「设置 → 系统诊断」会逐项检查 AI 服务、OpenSCAD、模型生成、
文件系统、网络等，出问题的地方旁边就有【自动修复】按钮。

详细使用说明见同目录的 README-用户.md（快速上手）与仓库 docs/USER_GUIDE.md（完整指南）。
本软件采用 MIT 许可证，全文见同目录的 LICENSE；
随包分发的第三方组件及其许可证见 LICENSE-THIRD-PARTY.txt 与 LICENSE-OpenSCAD-GPLv2.txt。
"""


def main() -> int:
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    target_dir = Path(sys.argv[1])
    version = sys.argv[2]
    built_at = sys.argv[3]

    target_dir.mkdir(parents=True, exist_ok=True)

    guide = INSTALL_GUIDE
    if version:
        guide = f"（版本 {version}　构建于 {built_at}）\n\n" + guide
    (target_dir / "安装说明.txt").write_text(guide, encoding="utf-8", newline="\r\n")

    print(f"已生成安装说明.txt（{len(guide)} 字符，UTF-8 + CRLF）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
